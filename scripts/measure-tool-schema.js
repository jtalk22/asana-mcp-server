#!/usr/bin/env node
// Tool-surface measurement + API doc generator.
//   node scripts/measure-tool-schema.js              # size table per ASANA_MCP_TOOLS profile
//   node scripts/measure-tool-schema.js --json       # machine-readable
//   node scripts/measure-tool-schema.js --markdown   # docs/API.md content on stdout
// An MCP client pays for the tools/list schema on every turn that carries it; sizes here
// are exact serialized bytes with a ~4-chars-per-token ESTIMATE (labelled as such).
import { TOOLS, filterTools } from '../lib/tools.js';

const advertised = (tools) => JSON.stringify(tools.map((t) => ({
  name: t.name, description: t.description, inputSchema: t.inputSchema, annotations: t.annotations,
})));

if (process.argv.includes('--markdown')) {
  const lines = [];
  lines.push('# Tool reference');
  lines.push('');
  lines.push(`> Generated by \`npm run api-docs\` from \`lib/tools.js\` — do not edit by hand. ${TOOLS.length} tools.`);
  lines.push('');
  lines.push('Badges: `RO` read-only (`readOnlyHint: true`) · `W` write · `DESTRUCTIVE` requires `confirm: true` and carries `destructiveHint`. Every tool declares MCP annotations, so clients that understand them can auto-allow reads and gate writes.');
  const groups = [
    ['Reads', (t) => t.annotations.readOnlyHint && !t.name.match(/morning_brief|user_queue|portfolio_rollup|board_rollup/)],
    ['Composites (one call, one answer)', (t) => /morning_brief|user_queue|portfolio_rollup|board_rollup|triage_inbox/.test(t.name)],
    ['Writes', (t) => !t.annotations.readOnlyHint && !t.annotations.destructiveHint && !/triage_inbox/.test(t.name)],
    ['Destructive (confirm-gated)', (t) => t.annotations.destructiveHint],
  ];
  const seen = new Set();
  for (const [title, pred] of groups) {
    const rows = TOOLS.filter((t) => pred(t) && !seen.has(t.name));
    rows.forEach((t) => seen.add(t.name));
    if (!rows.length) continue;
    lines.push('', `## ${title} (${rows.length})`, '');
    for (const t of rows.sort((a, b) => a.name.localeCompare(b.name))) {
      const badge = t.annotations.destructiveHint ? 'DESTRUCTIVE' : t.annotations.readOnlyHint ? 'RO' : 'W';
      const params = Object.entries(t.inputSchema.properties || {})
        .map(([k, v]) => `\`${k}\`${(t.inputSchema.required || []).includes(k) ? '*' : ''}`).join(' · ') || '—';
      lines.push(`### \`${t.name}\` \`${badge}\``, '', t.description, '', `Params: ${params}`, '');
    }
  }
  const missed = TOOLS.filter((t) => !seen.has(t.name));
  if (missed.length) throw new Error('ungrouped tools: ' + missed.map((t) => t.name).join(', '));
  console.log(lines.join('\n'));
  process.exit(0);
}

const profiles = ['all', 'read', 'write'];
const out = profiles.map((p) => {
  const tools = filterTools(p);
  const bytes = advertised(tools).length;
  return { profile: p, tools: tools.length, bytes, est_tokens: Math.round(bytes / 4) };
});
if (process.argv.includes('--json')) console.log(JSON.stringify(out, null, 2));
else for (const r of out) console.log(`${r.profile.padEnd(6)} ${String(r.tools).padStart(3)} tools  ${String(r.bytes).padStart(7)} bytes  ~${r.est_tokens} tokens (4-chars/token estimate)`);
